def _rel(v, r, floor):
    try:
        v = float(v)
    except Exception:
        return float("inf")
    return abs(v - r) / (abs(r) + floor) if math.isfinite(v) else float("inf")


def audit_se_table(m):
    worst, where = 0.0, None
    for (mw, mz, mh, al, xi, mu), r in SE_TABLE:
        dv = _rel(m.delta_r_se(mw, mz, mh, al, xi, mu), r, 1e-9)
        if dv > worst:
            worst, where = dv, (mw, mz, mh, xi, mu)
    return worst < 1e-10, f"class SE vs the auditor's independent derivation at {len(SE_TABLE)} points: worst {worst:.1e} at {where}"


def audit_vbw_table(m):
    worst, where = 0.0, None
    for (mw, mz, al, xi, mu), r in VBW_TABLE:
        dv = _rel(m.delta_r_vbw(mw, mz, al, xi, mu), r, 1e-9)
        if dv > worst:
            worst, where = dv, (mw, mz, xi, mu)
    return worst < 1e-9, f"class VBW vs (Denner total - auditor SE) [gauge independence, not independent] at {len(VBW_TABLE)} points: worst {worst:.1e} at {where}"


def audit_total_extreme_xi(m):
    worst = 0.0
    for p in ((80.38, 91.19, 125.0, 1 / 128.0), (75.0, 91.19, 300.0, 1 / 130.0)):
        t1 = m.delta_r_bos_xi(*p, 1.0)
        for xi in (1e-9, 1e-6, 1e-3, 0.05, 1e4, 1e6):
            worst = max(worst, _rel(m.delta_r_bos_xi(*p, xi), t1, 0.0))
    return worst < 1e-9, f"total at xi = 1e-9, 1e-6, 1e-3, 0.05, 1e4, 1e6 against xi = 1: worst relative {worst:.1e}"


def audit_landau_convention(m):
    ks = []
    for (mw, mz, mh, al, mu), c0 in LANDAU_C0:
        a4 = al / (4 * math.pi)
        try:
            ks.append((c0 - float(m.delta_r_se(mw, mz, mh, al, 0.0, mu))) / (0.75 * a4))
        except Exception as e:
            return False, f"SE at xi = 0 failed: {type(e).__name__}: {e}"
    spread = max(ks) - min(ks)
    ok = spread < 1e-7 and all(math.isfinite(k) and 0.5 <= k <= 1.5 for k in ks)
    return ok, f"Landau-gauge SE(0) = C0(mu) - (3/4)(alpha/4pi) kappa: kappa in [{min(ks):.10f}, {max(ks):.10f}] over {len(ks)} (point, mu) (one convention constant, 1/2..3/2)"


def audit_landau_log_slope(m):
    p = (80.38, 91.19, 125.0, 1 / 128.0)
    a4 = p[3] / (4 * math.pi)
    s1 = (m.delta_r_se(*p, 1e-8, p[0]) - m.delta_r_se(*p, 1e-10, p[0])) / math.log(100.0)
    dev = abs(s1 / (-0.75 * a4) - 1)
    return dev < 1e-4, f"dSE/dln xi at xi = 1e-8 ... 1e-10 over -(3/4) alpha/4pi: deviation {dev:.1e}"


