        """[SU(3)_L]^2 U(1)_X anomaly, sum of X over triplets and antitriplets (T(3) = T(3bar))."""
        Ng, nA, nT = _families(Nc)
        Xt, Xa = _quark_X(Qu, variant)
        return Ng * _lepton_X(variant) + Nc * (nT * Xt + nA * Xa)


