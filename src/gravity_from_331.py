def _solve(A, b):
    """Gaussian elimination with partial pivoting."""
    n = len(b)
    M = [row[:] + [b[i]] for i, row in enumerate(A)]
    for c in range(n):
        p = max(range(c, n), key=lambda r: abs(M[r][c]))
        M[c], M[p] = M[p], M[c]
        for r in range(c + 1, n):
            f = M[r][c] / M[c][c]
            for k in range(c, n + 1):
                M[r][k] -= f * M[c][k]
    x = [0.0] * n
    for r in range(n - 1, -1, -1):
        x[r] = (M[r][n] - sum(M[r][k] * x[k] for k in range(r + 1, n))) / M[r][r]
    return x


def heat_trace_S4(kind, t, lmax=2000):
    """Tr exp(-t D) on the unit round S^4 from the exact spectra. Scalar: l(l+3), degeneracy (l+1)(l+2)(2l+3)/6;
    Dirac D-slash^2: (n+2)^2, degeneracy 8 C(n+3,3) (both signs of D-slash); vector with ghosts: coexact 1-forms
    (l+1)(l+2) with degeneracy l(l+3)(2l+3)/2, exact 1-forms l(l+3) (l >= 1) with the scalar degeneracy, minus two
    scalars (the ghosts), zero mode included."""
    tot = 0.0
    for l in range(lmax):
        ds = (l + 1) * (l + 2) * (2 * l + 3) / 6
        if kind == "scalar":
            tot += ds * math.exp(-t * l * (l + 3))
        elif kind == "dirac":
            tot += 8 * math.comb(l + 3, 3) * math.exp(-t * (l + 2) ** 2)
        elif kind == "vector":
            if l >= 1:
                tot += l * (l + 3) * (2 * l + 3) / 2 * math.exp(-t * (l + 1) * (l + 2)) + ds * math.exp(-t * l * (l + 3))
            tot -= 2 * ds * math.exp(-t * l * (l + 3))
    return tot


def k1_from_spectrum(kind):
    """Fit (4 pi t)^2 K(t) / V = b0 + b1 t + b2 t^2 + b3 t^3 + b4 t^4 at small t; k1 = b1 / R with R = 12."""
    V = 8 * math.pi ** 2 / 3
    ts = [0.004 * (j + 1) for j in range(5)]
    ys = [(4 * math.pi * t) ** 2 * heat_trace_S4(kind, t) / V for t in ts]
    coef = _solve([[t ** k for k in range(5)] for t in ts], ys)
    return coef[1] / 12, coef[0]


