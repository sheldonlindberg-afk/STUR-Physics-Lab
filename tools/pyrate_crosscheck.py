#!/usr/bin/env python3
"""External cross-check of the 3-3-1 gauge beta functions with PyR@TE 3.

PyR@TE 3 (L. Sartore and I. Schienbein, arXiv:2007.12700;
https://github.com/LSartore/pyrate) derives the renormalization group
equations of any renormalizable model from its gauge groups, fields and Lagrangian. It
shares no code with this repository. Here it is given the 3-3-1 models of
src/m331_core.py as model files and asked for the gauge beta functions:

    two loops, with the top, exotic-quark and heavy-lepton Yukawa couplings;
    three loops, gauge and matter terms (no Yukawa or quartic couplings in the model).

PyR@TE also checks each Lagrangian for gauge invariance before computing.

Independence. PyR@TE's one- and two-loop results come from its own implementation of the
general formulas, on explicit tensors. Its three-loop gauge terms are based on the same
paper as src/m331_three_loop.py (Poole and Thomsen, arXiv:1906.04625), so at three loops
the agreement checks the implementation, not the formula.

Usage:  python3 tools/pyrate_crosscheck.py /path/to/pyrate     (a clone of the repository;
        needs PyYAML, sympy, h5py, numpy, scipy, matplotlib; a few minutes)
Writes: results/m331/pyrate/pyrate_crosscheck.json   (PyR@TE's coefficients as exact
        fractions) and results/m331/pyrate/*.model   (the model files it was given).
tests/test_331_pyrate.py compares the JSON with the repository's own coefficients, so the
test suite does not need PyR@TE.
"""
import json
import os
import re
import subprocess
import sys
from fractions import Fraction as F

import sympy as sp

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
sys.path.insert(0, os.path.join(ROOT, "src"))
import m331_core as C

OUT_DIR = os.path.join(ROOT, "results", "m331", "pyrate")
CASES = [(3, 3), (5, 5), (2, 4)]                 # (N_c, N_g); (7, 7) adds nothing new and is slow
TAG = {"-1/sqrt3": "minus", "+1/sqrt3": "plus"}


def frac(x):
    return str(F(x))


def model_file(Nc, variant, Ng, yukawas):
    """A PyR@TE model file for the 3-3-1 model of m331_core.model(Nc, variant, Ng).
    Right-handed fields carry their own charges (the core lists left-handed conjugates)."""
    _, _, scal, (Xt, Xa, Qu, Qd, Ng, nA) = C.model(Nc, variant, Ng)
    nT = Ng - nA                                              # quark generations in the triplet
    minus = variant == "-1/sqrt3"
    XL = F(-1, 3) if minus else F(-2, 3)
    QT, QD = (Qu, Qd) if minus else (Qd, Qu)                  # charge of the triplet's / anti-triplet's exotic
    col = f", SUc: {Nc}"
    f = [f"    L : {{Gen: {Ng}, Qnb: {{U1X: {frac(XL)}, SU3L: 3}}}},",
         f"    eR : {{Gen: {Ng}, Qnb: {{U1X: -1}}}},"]
    if not minus:
        f.append(f"    ER : {{Gen: {Ng}, Qnb: {{U1X: -1}}}},")
    f.append(f"    Q1 : {{Gen: 1, Qnb: {{U1X: {frac(Xt)}, SU3L: 3{col}}}}},")       # holds the top
    if nT > 1:
        f.append(f"    Qt : {{Gen: {nT - 1}, Qnb: {{U1X: {frac(Xt)}, SU3L: 3{col}}}}},")
    f.append(f"    Qa : {{Gen: {nA}, Qnb: {{U1X: {frac(Xa)}, SU3L: -3{col}}}}},")
    f.append(f"    tR : {{Gen: 1, Qnb: {{U1X: {frac(Qu)}{col}}}}},")
    f.append(f"    uR : {{Gen: {Ng - 1}, Qnb: {{U1X: {frac(Qu)}{col}}}}},")
    f.append(f"    dR : {{Gen: {Ng}, Qnb: {{U1X: {frac(Qd)}{col}}}}},")
    f.append(f"    T1 : {{Gen: 1, Qnb: {{U1X: {frac(QT)}{col}}}}},")              # exotic of Q1
    if nT > 1:
        f.append(f"    TR : {{Gen: {nT - 1}, Qnb: {{U1X: {frac(QT)}{col}}}}},")
    f.append(f"    DR : {{Gen: {nA}, Qnb: {{U1X: {frac(QD)}{col}}}}},")
    names = ["S1", "S2", "S3"]
    s = [f"    {n} : {{RealFields: [{n}r, {n}i], Norm: 1/sqrt(2), Qnb: {{U1X: {frac(x[2])}, SU3L: 3}}}},"
         for n, x in zip(names, scal)]
    X = {n: x[2] for n, x in zip(names, scal)}

    def scalar(charge):
        """The scalar triplet of U(1)_X charge `charge`, or its conjugate ('bar')."""
        for n in names:
            if X[n] == charge:
                return n
        for n in names:
            if X[n] == -charge:
                return n + "bar"
        raise ValueError(charge)

    y = []
    if yukawas:
        # psibar_L S psi_R is neutral iff X(S) = X(psi_L) - X(psi_R); triplets contract with a delta
        y.append(f"        yt : Q1bar[i,a] {scalar(Xt - Qu)}[i] tR[a],")
        y.append(f"        yT : Q1bar[i,a] {scalar(Xt - QT)}[i] T1[a],")
        y.append(f"        YD : Qabar[i,a] {scalar(Xa - QD)}[i] DR[a],")
        if not minus:
            y.append(f"        YE : Lbar[i] {scalar(XL + 1)}[i] ER,")
    return f"""# YAML 1.1
---
Author: generated by tools/pyrate_crosscheck.py from src/m331_core.py
Date: 15.11.2026
Name: m331_{TAG[variant]}_Nc{Nc}_Ng{Ng}{'' if yukawas else '_gauge'}
Groups: {{U1X: U1, SU3L: SU3, SUc: SU{Nc}}}

Fermions: {{
{chr(10).join(f)}
}}

RealScalars: {{
}}

ComplexScalars: {{
{chr(10).join(s)}
}}

Potential: {{

    Yukawas: {{
{chr(10).join(y)}
    }},

}}

Substitutions: {{
    g_U1X : gX,
    g_SU3L : gL,
    g_SUc : gc
}}
"""


def run(pyrate, text, name, loops):
    """Run PyR@TE on a model file; return {gauge coupling: {loop: sympy expression}}."""
    path = os.path.join(OUT_DIR, name + ".model")
    with open(path, "w") as fh:
        fh.write(text)
    res = os.path.join(pyrate, "results")
    # gauge couplings only ([gauge, Yukawa, quartic] loop orders); no terminal for PyR@TE's optional
    # pdflatex step to wait on
    r = subprocess.run([sys.executable, os.path.join(pyrate, "pyR@TE.py"), "-m", path, "-l", f"[{loops},0,0]",
                        "-no-tex", "-no-math", "-py", "-res", res], capture_output=True, text=True,
                       stdin=subprocess.DEVNULL)
    out = os.path.join(res, name, "PythonOutput", "RGEs.py")
    if not os.path.exists(out):
        raise RuntimeError(r.stdout[-3000:] + r.stderr[-3000:])
    if "gauge invariance" in r.stdout.lower() and "not gauge invariant" in r.stdout.lower():
        raise RuntimeError("PyR@TE reports a Lagrangian that is not gauge invariant:\n" + r.stdout[-2000:])
    src = open(out).read()
    betas = {}
    for g in ("gX", "gL", "gc"):
        body = re.search(rf"def beta_{g}\(nLoop.*?\n(.*?)(?=\ndef |\n\n#|\Z)", src, re.S).group(1)
        betas[g] = {}
        for n, expr in re.findall(r"if nLoop == (\d):\s*\n\s*return (.*)", body):
            betas[g][int(n)] = parse(expr)
    return betas


SYM = {n: sp.Symbol(n) for n in ("gX", "gL", "gc", "yt2", "yT2", "trYD", "trYE")}


def parse(expr):
    """PyR@TE's Python expression -> sympy, with |y|^2 and tr(Y+ Y) as plain symbols."""
    expr = re.sub(r"tr\(adjoint\(Y([DE])\)\*Y\1\)", r"trY\1", expr)
    expr = re.sub(r"abs\(y([tT])\)\*\*2", r"y\1 2", expr).replace("yt 2", "yt2").replace("yT 2", "yT2")
    expr = re.sub(r"y([tT])\*conjugate\(y\1\)|conjugate\(y([tT])\)\*y\2", lambda m: f"y{m.group(1) or m.group(2)}2", expr)
    expr = re.sub(r"\by([tT])\*\*2", r"y\1 2", expr).replace("yt 2", "yt2").replace("yT 2", "yT2")
    return sp.sympify(expr, locals=SYM, rational=True)


def coefficients(betas):
    """One-, two- and three-loop coefficients as exact fractions (strings)."""
    g = [SYM["gX"], SYM["gL"], SYM["gc"]]
    yuk = [SYM[k] for k in ("yt2", "yT2", "trYD", "trYE")]
    out = {"a": [], "b": [], "yukawa": {str(y): [] for y in yuk}, "c": []}
    for i, name in enumerate(("gX", "gL", "gc")):
        b1 = sp.expand(betas[name][1])
        out["a"].append(str(sp.Rational(b1.coeff(g[i], 3))))
        if 2 in betas[name]:
            b2 = sp.expand(betas[name][2] / g[i] ** 3)
            p = sp.Poly(b2, *g, *yuk)
            out["b"].append([str(p.coeff_monomial(g[j] ** 2)) for j in range(3)])
            for y in yuk:
                out["yukawa"][str(y)].append(str(-p.coeff_monomial(y)))
        if 3 in betas[name]:
            b3 = sp.Poly(sp.expand(betas[name][3] / g[i] ** 3), *g)
            out["c"].append([[str(b3.coeff_monomial(g[j] ** 2 * g[k] ** 2)) if j <= k else "0"
                              for k in range(3)] for j in range(3)])
    return out


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    pyrate = os.path.abspath(sys.argv[1])
    os.makedirs(OUT_DIR, exist_ok=True)
    commit = subprocess.run(["git", "-C", pyrate, "log", "-1", "--format=%H %ad", "--date=short"],
                            capture_output=True, text=True).stdout.strip()
    rows = []
    for variant in C.VARIANTS:
        for Nc, Ng in CASES:
            name = f"m331_{TAG[variant]}_Nc{Nc}_Ng{Ng}"
            two = coefficients(run(pyrate, model_file(Nc, variant, Ng, True), name, 2))
            three = coefficients(run(pyrate, model_file(Nc, variant, Ng, False), name + "_gauge", 3))
            assert three["a"] == two["a"] and three["b"] == two["b"]
            rows.append(dict(variant=variant, Nc=Nc, Ng=Ng, a=two["a"], b=two["b"], yukawa=two["yukawa"],
                             c=three["c"]))
            print(f"beta = {variant}, N_c = {Nc}, N_g = {Ng}: a = {two['a']}")
    json.dump(dict(pyrate_commit=commit, pyrate_version="PyR@TE 3.0", rows=rows),
              open(os.path.join(OUT_DIR, "pyrate_crosscheck.json"), "w"), indent=1)
    print("wrote", os.path.join(OUT_DIR, "pyrate_crosscheck.json"))


if __name__ == "__main__":
    main()
