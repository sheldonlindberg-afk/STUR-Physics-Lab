def weak_to_strong():
    st = 3
    banner("3  Weak to strong: the pion decay constant")
    GF = take(st, "G_F")
    f130 = weak.fpi_from_pion_decay()
    tree = inputs.GAMMA_PI_MUNU / (1 + inputs.DELTA_PI) * inputs.HBAR / inputs.E_CH / 1e9      # GeV
    back = weak.pion_decay_width(f130, GF, inputs.V_UD, inputs.M_MU, inputs.M_PIC)
    check("f_pi reproduces the measured pi -> mu nu rate through the derived width formula",
          rel(back, tree) < 1e-10, f"{back:.6e} vs {tree:.6e} GeV")
    lattice = inputs.F_PI * math.sqrt(2)
    print(f"   f_pi = {1e3 * f130:.3f} MeV, from G_F and the measured pi -> mu nu rate")
    info("f_pi against the lattice value", f"{1e3 * lattice:.1f} MeV: {100 * (f130 - lattice) / lattice:+.2f}%"
         " (no uncertainty on either in the inputs)")
    REPLACED.append(("pion decay constant f_pi", f"{1e3 * f130:.3f} MeV",
                     "G_F and the pion's weak decay (stage weak), in place of the lattice value"))
    give(st, "f_pi", f130)


