def black_holes():
    st = 8
    banner("8  Black holes: the strong field, and where evaporation ends")
    G, ell, mpl = take(st, "G"), take(st, "l"), take(st, "M_Pl")
    take(st, "diamond mass")
    c, gm = inputs.C_LIGHT, inputs.GM_SUN
    kb, kc = blackholes.kappa_from_spin_connection(1.0, 9.0)
    rb, rc = blackholes.sds_horizons(1.0, 9.0)

    def f(r):
        return 1 - 2 / r - r * r / 81

    kk = blackholes.killing_kappa(f, rb * (1 + 1e-6), 1e-8 * rb)
    check("surface gravity: step 7's spin connection and the Killing vector agree", rel(kb, kk) < 1e-4,
          f"{kb:.8f} vs {kk:.8f}")
    cone = blackholes.euclidean_cone_ratio(f, rb, 2 * math.pi / kb, 1e-7 * rb)
    check("the Euclidean horizon is smooth exactly at the Hawking period 2 pi/kappa", abs(cone - 1) < 1e-4, f"ratio {cone:.8f}")
    first, smarr = blackholes.kerr_first_law(Fraction(7, 2), Fraction(3, 5), 2, -3)
    check("Kerr obeys the first law and the Smarr relation exactly", first == 0 and smarr == 0)
    r_ph, b_c = blackholes.photon_sphere()
    r_i, L2, E2 = blackholes.isco()
    print(f"   photon sphere r = {r_ph:.6f} M, critical impact parameter {b_c:.6f} M;  innermost stable orbit r = {r_i:.6f} M")
    m_nar = blackholes.nariai_mass_kg(inputs.LAMBDA_SI)
    info("largest black hole that fits inside step 7's horizon", f"{m_nar:.3e} kg = {m_nar * G / gm:.3e} solar masses")

    # the shadows: theta_g = G M/(c^2 D) from the stars, against the EHT's from the ring
    def theta_g(m_sun, d_pc):
        return blackholes.shadow_uas(m_sun, d_pc) / (2 * b_c)

    fit("M87*: angular size G M/(c^2 D) from stellar dynamics, against the EHT ring",
        theta_g(inputs.M87_STARS[0], inputs.M87_STARS[2]), inputs.THETA_G_M87, "uas", "photon sphere, b_c")
    sgr = (theta_g(*inputs.SGRA_VLTI) + theta_g(*inputs.SGRA_KECK)) / 2
    fit("Sgr A*: the same, from stellar orbits", sgr, inputs.THETA_G_SGRA, "uas", "photon sphere, b_c")
    print(f"   shadow diameters: M87* {blackholes.shadow_uas(inputs.M87_STARS[0], inputs.M87_STARS[2]):.1f} uas,"
          f" Sgr A* {2 * b_c * sgr:.1f} uas")

    # GW250114: the ringdown of the remnant the inspiral predicts
    z = inputs.GW_Z[0]
    f220, d220 = blackholes.qnm_220(inputs.GW_MF * (1 + z), inputs.GW_CHIF)
    fit("GW250114 ringdown frequency (220 mode)", f220, inputs.F220, "Hz", "Kerr remnant (the mode formula is a quoted fit)")
    fit("GW250114 ringdown damping rate", d220, inputs.G220, "1/s", "Kerr remnant (the mode formula is a quoted fit)")
    a_f = blackholes.kerr_area_km2(inputs.GW_MF, inputs.GW_CHIF)
    a_i = blackholes.kerr_area_km2(inputs.GW_M1[0], 0.0) + blackholes.kerr_area_km2(inputs.GW_M2[0], 0.0)
    check("GW250114: the horizon area grew (Hawking's area law), even against the largest possible initial area",
          a_f > a_i, f"{a_i:.0f} -> {a_f:.0f} km^2")

    # Hawking temperature, and the end of evaporation
    m_sgr = inputs.SGRA_VLTI[0] * gm / G
    t_sgr = blackholes.hawking_K(m_sgr)
    info("Hawking temperature of Sgr A*", f"{t_sgr:.4e} K")
    m_pl_kg = mpl * 1e9 * inputs.E_CH / c ** 2
    info("the diamond", f"{take(st, 'diamond mass') / m_pl_kg:.1e} Planck masses, r_s = "
         f"{links.schwarzschild_radius(inputs.DESIGN_A_MASS):.1e} m: far too light to be a black hole")
    kT = links.planck_bh_kT_GeV()
    check("an evaporating hole ends at step 1's Planck mass, at k_B T = M_Pl/(8 pi)", rel(kT, mpl / (8 * math.pi)) < 1e-9,
          f"{kT:.4e} GeV")
