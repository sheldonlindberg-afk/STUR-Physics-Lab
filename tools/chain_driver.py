def unification():
    st = 1
    banner("1  Unification: SU(3)_C x SU(3)_L x U(1)_X -> the Standard Model -> electromagnetism")
    variant = "+1/sqrt3"
    # the quark charges are not put in: anomaly cancellation fixes them for each number of colours
    Qu, Qd = gauge331.quark_charges(3)
    Qu5, Qd5 = gauge331.quark_charges(5)
    print(f"   quark charges from anomaly cancellation: N_c = 3 -> ({Qu}, {Qd});  N_c = 5 -> ({Qu5}, {Qd5})")
    REPLACED.append(("quark charges Q_u, Q_d", f"{Qu}, {Qd}", "anomaly cancellation (stage gauge331)"))
    for var in gauge331.VARIANTS:
        qp, qn, qe, qnu = links.matter_charges(3, var)
        check(f"matter is exactly neutral, beta = {var}: q_p + q_e = {qp + qe}, q_n = {qn}, Q_nu = {qnu}",
              qp + qe == 0 and qn == 0 and qnu == 0)
    qp, qn, qe, qnu = links.matter_charges(3, variant)
    b = Fraction(1, 6)
    check("q_p + q_e equals the gauge anomaly per generation, identically in (N_c, b, X_L, X_t)",
          all(links.qp_qe_minus_anomaly(n, bb, xl, xt) == 0
              for n in (3, 5, 7) for bb in (b, -b, Fraction(2, 7)) for xl in (Fraction(-1, 3), Fraction(5, 9))
              for xt in (Fraction(0), Fraction(4, 11))))

    # the measured couplings enter here
    G = inputs.G_NEWTON
    mpl = links.planck_mass_GeV(G, inputs.HBAR, inputs.C_LIGHT)
    print(f"   Planck mass from the measured G: {mpl:.6e} GeV")

    # the number of colours is not put in either: the U(1)_X Landau pole must lie above the Planck mass
    # for the theory to reach it, and N_c = 5's pole lies far below
    for var in gauge331.VARIANTS:
        p3, p5 = running.landau_pole(3, var), running.landau_pole(5, var)
        lo, hi = links.g_window_from_rungs(var)
        print(f"   beta = {var}: one-loop Landau poles {p3:.3e} GeV (N_c = 3), {p5:.3e} GeV (N_c = 5);"
              f"  = {p3 / mpl:.3g} and {p5 / mpl:.3g} M_Pl")
        print(f"      G window in which pole_5 < M_Pl < pole_3: {lo:.3g} < G/G_measured < {hi:.3g}")
        if var == variant:
            check(f"N_c = 3 is selected against the Planck mass (beta = {var}): pole_5 < M_Pl < pole_3",
                  p5 < mpl < p3 and lo < 1 < hi)
            wlo, whi = links.g_window(p3, p5, mpl)
            check("the G window is the one the poles and M_Pl give by hand-off", rel(wlo, lo) < 1e-12 and rel(whi, hi) < 1e-12)
    REPLACED.append(("number of colours N_c", "3", "the Landau poles against M_Pl (stages running, links); one loop"))

    # the electroweak gauge bosons, from the mass matrix
    alpha_mz = 1 / inputs.ALPHA_MZ_INV
    g = math.sqrt(4 * math.pi * alpha_mz / inputs.S2_MZ)
    gX = toolkit.bisect(lambda x: gauge331.inv_e2(variant, g, x) - 1 / (4 * math.pi * alpha_mz), 1e-3, 50.0)
    v = gauge331.vev_from_GF(inputs.G_F)
    v1 = v2 = v / math.sqrt(2)            # a choice: the ratio v1/v2 is not fixed by anything here
    n = gauge331.photon_direction(variant, g, gX)

    def spectrum(w):
        return [math.sqrt(abs(x)) for x in toolkit.eigvalsh(gauge331.mass_matrix(variant, g, gX, w, v1, v2))]

    w = toolkit.bisect(lambda x: spectrum(x)[4] - inputs.MU_331, v, 1e3 * inputs.MU_331)
    M = gauge331.mass_matrix(variant, g, gX, w, v1, v2)
    ev = spectrum(w)
    worst = max(abs(sum(M[i][j] * n[j] for j in range(9))) for i in range(9)) / max(ev) ** 2
    check("the photon is massless: M.n = 0 for the derived direction n", worst < 1e-12, f"|M n|/M_max^2 = {worst:.1e}")
    mz_matrix = math.sqrt(gauge331.neutral_masses(variant, g, gX, w, v1, v2)[0])
    mz_inf = math.sqrt(gauge331.neutral_masses(variant, g, gX, 4000 * v, v1, v2)[0])
    mz = gauge331.mz_tree(inputs.G_F, inputs.ALPHA_MZ_INV, inputs.S2_MZ)
    check("the mass matrix's Z, with the 3-3-1 scale taken to infinity, is the tree-level formula's",
          rel(mz_inf, mz) < 1e-7, f"{mz_inf:.6f} vs {mz:.6f} GeV")
    print(f"   g = {g:.5f} (from alpha(M_Z), sin^2 theta_W);  g_X = {gX:.5f} (fixed by the photon's coupling);"
          f"  v = {v:.3f} GeV (from G_F)")
    print(f"   3-3-1 scale w = {w:.1f} GeV, set so the lightest new gauge boson weighs MU_331 = {inputs.MU_331:.0f} GeV"
          " (a choice)")
    print(f"   spectrum (GeV): photon {ev[0]:.1e}, W {ev[1]:.4f}, Z {mz_matrix:.4f}, new bosons {ev[4]:.1f}"
          f" to {ev[7]:.1f}, Z' {ev[8]:.1f}")
    d = (mz_matrix - inputs.MZ_MEAS) / inputs.MZ_MEAS
    info("M_Z at tree level", f"{mz_matrix:.4f} GeV against the measured {inputs.MZ_MEAS:.4f} GeV: {100 * d:+.2f}%."
         " This is far outside the measurement's error; loop corrections, which are of this size,"
         " are not in the chain")

    give(st, "G", G)
    give(st, "Q_u", Qu)
    give(st, "Q_d", Qd)
    give(st, "N_c", 3)
    give(st, "q_p + q_e", qp + qe)
    give(st, "M_Pl", mpl)
    give(st, "G_F", inputs.G_F)
    give(st, "M_V", inputs.MU_331)


