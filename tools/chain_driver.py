def gauge_gravity():
    st = 7
    banner("7  Gravity as a broken gauge theory: SO(4,1) -> SO(3,1)")
    take(st, "G")
    take(st, "phase")
    Lam = inputs.LAMBDA_SI
    ell = desitter.ell_from_lambda(Lam)
    x = (0.3, 5.0, 1.1, 0.4)
    kept = desitter.unbroken_generators([0, 0, 0, 0, 1])
    check("the vacuum direction leaves the 6 Lorentz generators unbroken", len(kept) == 6, f"{kept}")
    res = desitter.curvature_split_residual(1.0, 9.0, x)
    check("the SO(4,1) curvature splits into the Lorentz curvature and the cosmological term", res < 1e-9, f"residual {res:.1e}")
    flat = desitter.ds_curvature_max(9.0, x)
    check("de Sitter space is the gauge theory's flat connection (F = 0)", flat < 1e-9, f"max |F| = {flat:.1e}")
    cR, cV = desitter.action_coefficients(1.0, 9.0, x)
    check("the action reduces to Einstein-Hilbert with a cosmological constant: (cR, cV) = (2, 24)",
          abs(cR - 2) < 1e-9 and abs(cV - 24) < 1e-9, f"({cR:.12g}, {cV:.12g})")
    R = desitter.ricci_scalar(1.0, 9.0, x)
    check("Lambda l^2 = 3: the Ricci scalar on Schwarzschild-de Sitter is 12/l^2 = 4 Lambda", abs(R * 81 / 12 - 1) < 1e-9,
          f"R l^2 = {R * 81:.10f}")
    check("l = sqrt(3/Lambda)", rel(ell, math.sqrt(3 / Lam)) < 1e-12)
    coup = desitter.mm_coupling(Lam, inputs.L_PLANCK)
    print(f"   de Sitter radius l = {ell:.4e} m from the measured Lambda;  coupling l^2/l_P^2 = {coup:.3e}")
    give(st, "l", ell)


