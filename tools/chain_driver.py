def lab_electromagnetism():
    st = 5
    banner("5  Electromagnetism in the lab: what could hide gravity between two diamonds")
    take(st, "G")
    net = take(st, "q_p + q_e")
    check("the derived charge imbalance is inside the measured bound |q_p + q_e| < 1e-21 e",
          abs(net) < inputs.EPS_PE_BOUND, f"derived {net}, exactly")
    need = links.neutrality_per_nucleon(inputs.DESIGN_A_MASS)
    print(f"   net charge the experiment can tolerate: {need:.4e} e per nucleon"
          f"  ({need / inputs.EPS_PE_BOUND:.0f} times looser than that bound)")
    check("the Casimir-Polder integral is exactly 23/4", casimir.cp_integral() == Fraction(23, 4), str(casimir.cp_integral()))
    gap = casimir.casimir_safe_gap(inputs.GAP_BASELINE_MASS, inputs.GAP_BASELINE_DX, inputs.GAP_BASELINE_TAU,
                                   inputs.GAP_FRACTION)
    print(f"   smallest gap at which the Casimir phase is under {inputs.GAP_FRACTION:g} of gravity's: {1e6 * gap:.2f} um")
    REPLACED.append(("gap between the diamonds", f"{1e6 * gap:.2f} um", "the Casimir-Polder force (stage casimir)"))
    give(st, "neutrality needed", need)
    give(st, "gap", gap)


