def strong():
    st = 4
    banner("4  The strong force: chiral symmetry breaking")
    Qu, Qd, Nc = take(st, "Q_u"), take(st, "Q_d"), take(st, "N_c")
    alpha0, f130 = take(st, "alpha(0)"), take(st, "f_pi")
    F = f130 / math.sqrt(2)                      # the ~92 MeV convention

    check("three Goldstone bosons: the O(4) sigma model's vacuum has 3 zero modes", chiral.goldstone_count(2.0, 1.0) == 3)
    worst = chiral.tensor_identity_residual((0.3, -1.1, 0.7))
    check("pion exchange has the nuclear force's tensor structure", worst < 1e-12, f"residual {worst:.1e}")

    # the pion mass from the quark masses
    args = (inputs.M_UD_FLAG, inputs.COND_13, inputs.FPI_OVER_F, inputs.LBAR3)
    errs = (inputs.M_UD_FLAG_ERR, inputs.COND_13_ERR, inputs.FPI_OVER_F_ERR, inputs.LBAR3_ERR)
    mpi = chiral.chpt_mpi(*args, F)
    check("the O(p^4) pion mass by hand-off equals the build's own route", rel(mpi, chiral.chpt_mpi_from_rungs()) < 1e-12)

    def shifted(i, sign):
        a = list(args)
        a[i] += sign * errs[i]
        return chiral.chpt_mpi(*a, F)

    dm = [(shifted(i, +1) - shifted(i, -1)) / 2 for i in range(4)]
    sig_m = math.sqrt(sum(x * x for x in dm))
    lo_m = chiral.gmor_mpi(inputs.MU_PLUS_MD, inputs.COND_13, F)
    print(f"   pion mass: leading order (GMOR) {1e3 * lo_m:.1f} MeV;  O(p^4) {1e3 * mpi:.2f} +- {1e3 * sig_m:.2f} MeV"
          " (the error is the lattice inputs')")
    fit("pion mass at O(p^4), against the neutral pion", 1e3 * mpi, (1e3 * inputs.M_PI0, 0.0), "MeV",
        "f_pi", extra_sigma=1e3 * sig_m)
    rng = inputs.HBARC_GEV_FM / mpi
    print(f"   range of the nuclear force, hbar c/m_pi with the derived mass: {rng:.3f} fm"
          f"  (Yukawa: V({rng:.2f} fm)/V(0.1 fm) = {chiral.yukawa(rng, 1 / rng) / chiral.yukawa(0.1, 1 / rng):.3g})")

    # pi0 -> gamma gamma: the anomaly, with the charges of step 1 and the f_pi of step 3
    width = links.pi0_width_eV(alpha0, F, inputs.M_PI0, Nc, Qu, Qd)
    check("the pi0 width by hand-off equals the build's own route", rel(width, links.pi0_width_from_rungs()) < 1e-12)
    fit("pi0 -> gamma gamma width", width, (inputs.GAMMA_PI0, inputs.GAMMA_PI0_ERR), "eV", "Q_u, Q_d, N_c, f_pi")
    w5 = links.pi0_width_eV(alpha0, F, inputs.M_PI0, 5, *gauge331.quark_charges(5))
    info("the same width with 5 colours and their anomaly-fixed charges", f"{w5:.4f} eV: identical, because"
         f" N_c (Q_u^2 - Q_d^2) = {Nc * (Qu * Qu - Qd * Qd)} for every N_c. This width does not count colours;"
         " step 1's Landau poles do")
    # and with the pion mass derived too: nothing measured in the formula but alpha
    width_d = links.pi0_width_eV(alpha0, F, mpi, Nc, Qu, Qd)
    fit("the same width with the derived pion mass in place of the measured one", width_d,
        (inputs.GAMMA_PI0, inputs.GAMMA_PI0_ERR), "eV", "Q_u, Q_d, N_c, f_pi, m_pi",
        extra_sigma=3 * width_d * sig_m / mpi)

    # the pion-nucleon coupling
    gpi = chiral.goldberger_treiman(inputs.G_A, inputs.M_N, F)
    fit("pion-nucleon coupling (Goldberger-Treiman)", gpi, (inputs.G_PINN_EMP, inputs.G_PINN_ERR), "", "f_pi")
    REPLACED.append(("pion mass m_pi", f"{1e3 * mpi:.1f} MeV", "O(p^4) chiral perturbation theory with the derived f_pi"
                     " (stage chiral; the formula is quoted, the lattice constants are inputs)"))
    give(st, "m_pi O(p^4)", mpi)
    give(st, "pi0 width", width)


