def photon():
    st = 2
    banner("2  Electroweak to the photon")
    aY, a2 = running.couplings_at(inputs.MZ_MEAS)
    check("at M_Z the two electroweak couplings add up to the photon's: 1/alpha_Y + 1/alpha_2 = 1/alpha",
          rel(aY + a2, inputs.ALPHA_MZ_INV) < 1e-12, f"{aY:.4f} + {a2:.4f} = {aY + a2:.4f}")
    alpha0 = inputs.ALPHA_0
    info("alpha at zero momentum", f"1/alpha(0) = {1 / alpha0:.6f}, a measured input here. Running it down from M_Z"
         " needs the measured hadronic vacuum polarization; the blind build has no stage for that")
    give(st, "alpha(0)", alpha0)


