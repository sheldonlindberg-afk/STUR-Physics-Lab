def lab_gravity():
    st = 6
    banner("6  Gravity in the lab: one-graviton exchange between the diamonds")
    take(st, "G")
    gap = take(st, "gap")
    h00, hii = graviton.point_mass_metric()
    check("the exchange gives the Newtonian potential and light bending twice Newton's (h00 = hii = 2)",
          h00 == 2 and hii == 2, f"h00 = {h00}, hii = {hii} in GM/(c^2 r)")
    phase = graviton.entangling_phase(inputs.DESIGN_A_MASS, inputs.DESIGN_A_DX, inputs.DESIGN_A_HOLD,
                                      inputs.DESIGN_A_RAMP, gap)
    check("the phase at the handed-on gap equals the build's own route", rel(phase, graviton.design_phase()) < 1e-12)
    info("entangling phase of design A", f"{phase:.4f} rad. A prediction: the experiment has not been done")
    give(st, "phase", phase)
    give(st, "diamond mass", inputs.DESIGN_A_MASS)


