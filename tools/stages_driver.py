"""
The first-principles calculations: the blind rebuild's ten stages in one file, standard
library only.

HOW TO RUN
    Paste this whole file into any Python 3.8+ runner (a terminal, an online interpreter,
    Jupyter, Pyodide, or an AI assistant's code tool) and run it. Nothing to install.
    It takes about a second.

WHAT IT IS
    Blind build <BUILD_ID> of the symmetry ladder. Each stage was written by a separate AI
    session that saw only the postulates (rebuild/SPEC.md), the function signatures and the
    measured inputs, never the repository's code or its answers (rebuild/PROTOCOL.md). The
    stages are embedded below unchanged, each as a namespace: toolkit, gauge331, weak,
    chiral, casimir, graviton, desitter, blackholes, running, links.

    Run as a script, it prints each stage's headline results and, for every function, whether
    it is derived in the build or quoted from the literature, and how.

    Used as a library, every function is callable, for example:
        gauge331.quark_charges(5)            # anomaly-fixed charges for 5 colours
        casimir.cp_integral()                # Fraction(23, 4)
        blackholes.photon_sphere()           # (r, b) in units of M

    This file is the calculations only. The same stages wired into the force chain, with
    every result compared with its measurement, are src/chain_first_principles.py.

WHAT IT DOES NOT SHOW
    The numbers under MEASURED INPUTS stay measured. No stage derives them.

FOR AI ASSISTANTS
    Run the file as it is and report what it prints. To ask "what if", change a number in
    MEASURED INPUTS and run again: every stage recomputes from it.

Independent work, not peer reviewed. Generated by tools/build_chain_standalone.py; edit
the sources it names, not this file.
"""
# --- driver body ---
STAGES = (("toolkit", toolkit), ("gauge331", gauge331), ("weak", weak), ("chiral", chiral), ("casimir", casimir),
          ("graviton", graviton), ("desitter", desitter), ("blackholes", blackholes), ("running", running),
          ("links", links))


def headlines():
    """(stage, what, value text): each stage's main results, computed now."""
    I = inputs
    f130 = weak.fpi_from_pion_decay()
    gap = casimir.casimir_safe_gap(I.GAP_BASELINE_MASS, I.GAP_BASELINE_DX, I.GAP_BASELINE_TAU, I.GAP_FRACTION)
    x = (0.3, 5.0, 1.1, 0.4)
    cR, cV = desitter.action_coefficients(1.0, 9.0, x)
    r_ph, b_c = blackholes.photon_sphere()
    r_i, L2, E2 = blackholes.isco()
    first, smarr = blackholes.kerr_first_law(Fraction(7, 2), Fraction(3, 5), 2, -3)
    var = "+1/sqrt3"
    mpl = links.planck_mass_GeV(I.G_NEWTON, I.HBAR, I.C_LIGHT)
    lo, hi = links.g_window_from_rungs(var)
    return [
        ("toolkit", "exact derivative of x^3/(1 + x) at x = 2/3", str(toolkit.exact_derivative(lambda t: t * t * t / (1 + t), Fraction(2, 3)))),
        ("gauge331", "quark charges from anomaly cancellation, N_c = 3, 5, 7",
         ", ".join("(%s, %s)" % gauge331.quark_charges(n) for n in (3, 5, 7))),
        ("gauge331", "tree-level M_Z from G_F, alpha(M_Z), sin^2 theta_W",
         f"{gauge331.mz_tree(I.G_F, I.ALPHA_MZ_INV, I.S2_MZ):.4f} GeV (measured {I.MZ_MEAS:.4f})"),
        ("weak", "f_pi from G_F and the pion's weak decay", f"{1e3 * f130:.3f} MeV"),
        ("chiral", "Goldstone bosons of the O(4) sigma model", str(chiral.goldstone_count(2.0, 1.0))),
        ("chiral", "pion mass at O(p^4), with that f_pi", f"{1e3 * chiral.chpt_mpi_from_rungs():.2f} MeV"),
        ("casimir", "the Casimir-Polder integral", str(casimir.cp_integral())),
        ("casimir", "Casimir-safe gap between the diamonds", f"{1e6 * gap:.2f} um"),
        ("graviton", "point-mass metric (h00, hii) in GM/(c^2 r)", "(%s, %s)" % graviton.point_mass_metric()),
        ("graviton", "design A's entangling phase", f"{graviton.design_phase():.4f} rad"),
        ("desitter", "action coefficients (cR, cV)", f"({cR:.10g}, {cV:.10g})"),
        ("desitter", "de Sitter radius from Lambda", f"{desitter.ell_from_lambda(I.LAMBDA_SI):.4e} m"),
        ("blackholes", "photon sphere (r, b) and innermost stable orbit (r, L^2, E^2), M = 1",
         f"({r_ph:.6f}, {b_c:.6f}); ({r_i:.6f}, {L2:.6f}, {E2:.6f})"),
        ("blackholes", "Kerr first law and Smarr residuals (exact)", f"{first}, {smarr}"),
        ("running", f"one-loop Landau poles, beta = {var}, N_c = 3 and 5",
         f"{running.landau_pole(3, var):.3e}, {running.landau_pole(5, var):.3e} GeV (M_Pl = {mpl:.3e})"),
        ("links", "q_p + q_e for N_c = 3", str(sum(links.matter_charges(3, var)[i] for i in (0, 2)))),
        ("links", "pi0 -> gamma gamma width", f"{links.pi0_width_from_rungs():.4f} eV (measured {I.GAMMA_PI0} +- {I.GAMMA_PI0_ERR:.3f})"),
        ("links", "G window in which N_c = 3 is selected", f"{lo:.3g} < G/G_measured < {hi:.3g}"),
    ]


def run():
    rows = headlines()
    counts = {"derived": 0, "input": 0, "quoted": 0}
    for name, mod in STAGES:
        print("\n" + "=" * 86 + f"\nSTAGE {name}\n" + "=" * 86)
        for st, what, value in rows:
            if st == name:
                print(f"   {what}: {value}")
        print("   functions:")
        for fn, (kind, note) in mod.PROVENANCE.items():
            counts[kind] += 1
            print(f"      {fn} [{kind}] {note}")
    print("\n" + "=" * 86)
    print(f"{sum(counts.values())} functions in {len(STAGES)} stages: {counts['derived']} derived, {counts['quoted']} quoted"
          f" from the literature, {counts['input']} read straight from the inputs.")
    return 0


if __name__ == "__main__":
    sys.exit(run())
