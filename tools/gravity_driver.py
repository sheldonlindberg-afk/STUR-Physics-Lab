def planck_mass_GeV():
    """M_Pl = sqrt(hbar c / G), in GeV, from the measured G (CODATA)."""
    joule_per_gev = 1e9 * inputs.E_CH
    return math.sqrt(inputs.HBAR * inputs.C_LIGHT / inputs.G_NEWTON) * inputs.C_LIGHT ** 2 / joule_per_gev


def species(variant, nc=3):
    """(real scalars, Weyl fermions, vectors) above the 3-3-1 scale: stage 1's field list and its gauge group."""
    n_w = n_s = 0
    for kind, mult, dim, _ in running._fields_331(nc, variant):
        if kind == "weyl":
            n_w += int(mult) * dim
        else:
            n_s += 2 * int(mult) * dim
    return n_s, n_w, (nc * nc - 1) + 8 + 1


def poles(variant):
    return {"one loop": running.landau_pole(3, variant), "three loops": inputs.POLES_331[variant][0]}


