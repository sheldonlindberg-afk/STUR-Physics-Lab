def _solve(A, b):
    """Gaussian elimination with partial pivoting."""
    n = len(b)
    M = [row[:] + [b[i]] for i, row in enumerate(A)]
    for c in range(n):
        p = max(range(c, n), key=lambda r: abs(M[r][c]))
        M[c], M[p] = M[p], M[c]
        for r in range(c + 1, n):
            f = M[r][c] / M[c][c]
            for k in range(c, n + 1):
                M[r][k] -= f * M[c][k]
    x = [0.0] * n
    for r in range(n - 1, -1, -1):
        x[r] = (M[r][n] - sum(M[r][k] * x[k] for k in range(r + 1, n))) / M[r][r]
    return x


def heat_trace_S4(kind, t, lmax=2000):
    """Tr exp(-t D) on the unit round S^4 from the exact spectra. Scalar: l(l+3), degeneracy (l+1)(l+2)(2l+3)/6;
    Dirac D-slash^2: (n+2)^2, degeneracy 8 C(n+3,3) (both signs of D-slash); vector with ghosts: coexact 1-forms
    (l+1)(l+2) with degeneracy l(l+3)(2l+3)/2, exact 1-forms l(l+3) (l >= 1) with the scalar degeneracy, minus two
    scalars (the ghosts), zero mode included."""
    tot = 0.0
    for l in range(lmax):
        ds = (l + 1) * (l + 2) * (2 * l + 3) / 6
        if kind == "scalar":
            tot += ds * math.exp(-t * l * (l + 3))
        elif kind == "dirac":
            tot += 8 * math.comb(l + 3, 3) * math.exp(-t * (l + 2) ** 2)
        elif kind == "vector":
            if l >= 1:
                tot += l * (l + 3) * (2 * l + 3) / 2 * math.exp(-t * (l + 1) * (l + 2)) + ds * math.exp(-t * l * (l + 3))
            tot -= 2 * ds * math.exp(-t * l * (l + 3))
    return tot


def k1_from_spectrum(kind):
    """Fit (4 pi t)^2 K(t) / V = b0 + b1 t + b2 t^2 + b3 t^3 + b4 t^4 at small t; k1 = b1 / R with R = 12."""
    V = 8 * math.pi ** 2 / 3
    ts = [0.004 * (j + 1) for j in range(5)]
    ys = [(4 * math.pi * t) ** 2 * heat_trace_S4(kind, t) / V for t in ts]
    coef = _solve([[t ** k for k in range(5)] for t in ts], ys)
    return coef[1] / 12, coef[0]


def part3(mpl):
    banner("PART 3  Route B: Newton's constant induced by stage 1's own fields (campaign induced_g, accepted)")
    print("   Sakharov: there is no gravity term to begin with. Integrating out the quantum fields on a curved")
    print("   background produces one. With a proper-time cutoff kappa, each field adds k1 x kappa^2/(2 pi) to 1/G,")
    print("   with k1 the coefficient of R in its heat kernel; fermions enter with a minus sign.\n")
    print("   (a) the per-field coefficient k1, from the blind build, against the exact spectra on a round S^4:")
    for kind, label in (("scalar", "real scalar (xi = 0)"), ("dirac", "Dirac fermion"), ("vector", "gauge vector + ghosts")):
        k_build = induced_g.k1(kind, 4)
        k_spec, b0 = k1_from_spectrum(kind)
        check(f"{label:22s} k1 = {k_build:+.6f}, from its spectrum {k_spec:+.6f}", abs(k_build - k_spec) < 1e-6)
    print("\n   (b) what each field does to 1/G (units of kappa^2):")
    contrib = {"scalar": induced_g.inv_G(1.0, 1, 0, 0), "Weyl fermion": induced_g.inv_G(1.0, 0, 1, 0),
               "gauge vector": induced_g.inv_G(1.0, 0, 0, 1)}
    for k, v in contrib.items():
        print(f"      one {k:12s}: {v:+.5f}  ({'attractive' if v > 0 else 'repulsive'})")
    check("scalars and fermions induce attractive gravity, gauge vectors repulsive (proper-time cutoff)",
          contrib["scalar"] > 0 and contrib["Weyl fermion"] > 0 and contrib["gauge vector"] < 0)

    print("\n   (c) stage 1's fields, cut off at its own U(1)_X pole:")
    band = {}
    for var in gauge331.VARIANTS:
        n_s, n_w, n_v = species(var)
        rows = []
        for xi in (0.0, 1 / 6):
            for name, p in poles(var).items():
                m = induced_g.mpl(p, n_s, n_w, n_v, xi)
                rows.append(m)
                print(f"      beta = {var:8s}, xi = {'0  ' if xi == 0 else '1/6'}, {name:11s} pole:"
                      + (f" induced M_Pl = {m:.3e} GeV = {m / mpl:.3g} x measured" if m else " no positive G"))
        band[var] = rows
    sel = [m for m in band["+1/sqrt3"] if m]
    lo, hi = min(sel) / mpl, max(sel) / mpl
    check(f"beta = +1/sqrt3: the measured G lies in the band its fields induce (M_Pl {lo:.2f} to {hi:.2f} x measured,"
          f" G {1 / hi ** 2:.2f} to {1 / lo ** 2:.1f} x measured)", lo <= 1 <= hi, tag="model")
    other = [m for m in band["-1/sqrt3"] if m]
    check("beta = -1/sqrt3 cannot induce it: its pole is 10^10 times too high", all(m / mpl > 1e5 for m in other),
          f"closest {min(other) / mpl:.1e} x measured", tag="model")
    n5 = species("+1/sqrt3", 5)
    m5 = induced_g.mpl(running.landau_pole(5, "+1/sqrt3"), *n5, 0.0)
    check("N_c = 5 at its own pole cannot induce it", m5 is not None and m5 / mpl < 1e-3,
          f"{n5[2]} vectors, {n5[1]} Weyl, {n5[0]} scalars: induced M_Pl {m5:.2e} GeV = {m5 / mpl:.1e} x measured", tag="model")
    return sel


